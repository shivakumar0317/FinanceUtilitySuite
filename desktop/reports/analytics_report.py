        dashboard=workbook["Dashboard"]; data=workbook["Chart Data"]
        holdings_rows=min(len(self.dataframe),10)+1
        bar=BarChart(); bar.type="bar"; bar.style=10; bar.title="Top Holdings by Current Value"; bar.x_axis.title="Current Value"; bar.height=7; bar.width=13
        bar.add_data(Reference(data,min_col=2,min_row=1,max_row=holdings_rows),titles_from_data=True); bar.set_categories(Reference(data,min_col=1,min_row=2,max_row=holdings_rows)); dashboard.add_chart(bar,"A20")
        sector_rows=len(self.sector_data)+1
        pie=PieChart(); pie.title="Sector Allocation"; pie.height=7; pie.width=11
        pie.add_data(Reference(data,min_col=9,min_row=1,max_row=sector_rows),titles_from_data=True); pie.set_categories(Reference(data,min_col=8,min_row=2,max_row=sector_rows)); pie.dataLabels=DataLabelList(); pie.dataLabels.showPercent=True; dashboard.add_chart(pie,"F20")
        if not self.monthly_data.empty:
            ws=workbook["Monthly Returns"]
            rows=len(self.monthly_data)+1
            monthly=BarChart(); monthly.type="col"; monthly.style=10; monthly.title="Monthly Returns"; monthly.y_axis.title="Return %"; monthly.height=7; monthly.width=13
            monthly.add_data(Reference(data,min_col=15,min_row=1,max_row=rows),titles_from_data=True); monthly.set_categories(Reference(data,min_col=13,min_row=2,max_row=rows)); ws.add_chart(monthly,"A12")
        if not self.growth_data.empty:
            ws=workbook["Performance Summary"]
            rows=len(self.growth_data)+1
            line=LineChart(); line.style=13; line.title="Portfolio Growth"; line.y_axis.title="Portfolio Value"; line.height=8; line.width=15
            line.add_data(Reference(data,min_col=18,min_row=1,max_row=rows),titles_from_data=True); line.set_categories(Reference(data,min_col=17,min_row=2,max_row=rows)); ws.add_chart(line,"D4")
        sector_ws=workbook["Sector Analysis"]
        return_bar=BarChart(); return_bar.type="col"; return_bar.style=10; return_bar.title="Sector Return %"; return_bar.y_axis.title="Return %"; return_bar.height=7; return_bar.width=13
        return_bar.add_data(Reference(data,min_col=11,min_row=1,max_row=sector_rows),titles_from_data=True); return_bar.set_categories(Reference(data,min_col=8,min_row=2,max_row=sector_rows)); sector_ws.add_chart(return_bar,"A12")
