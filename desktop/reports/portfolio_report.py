    def _create_chart_data_sheet(self, writer: pd.ExcelWriter) -> None:
        ws = writer.book.create_sheet("Chart Data")
        ws.sheet_view.showGridLines = False

        total_value = float(self.dataframe["Current Value"].sum())

        holding_allocation = self.dataframe[
            ["Symbol", "Current Value"]
        ].sort_values("Current Value", ascending=False).copy()
        holding_allocation["Allocation %"] = (
            holding_allocation["Current Value"] / total_value * 100
            if total_value else 0.0
        )

        top_holdings = holding_allocation.head(10).copy()

        profit_loss = self.dataframe[
            ["Symbol", "Profit"]
        ].sort_values("Profit", ascending=False).head(15)

        sector = (
            self.dataframe.groupby("Sector", as_index=False)["Current Value"]
            .sum()
            .sort_values("Current Value", ascending=False)
        )

        self._write_dataframe(ws, holding_allocation, 1, 1)
        self._write_dataframe(ws, profit_loss, 1, 5)
        self._write_dataframe(ws, top_holdings, 1, 8)
        self._write_dataframe(ws, sector, 1, 12)

